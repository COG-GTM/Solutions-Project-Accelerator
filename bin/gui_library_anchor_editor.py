"""
Modal editor for configuring anchor points on ACM/PlantPAx library symbols.

The dialog renders a single library symbol's SVG at a comfortable working
scale and lets the user place anchor points, drag to reposition, delete,
and pick a direction (TOP/BOTTOM/LEFT/RIGHT) via the four dedicated
direction-icon toolbar buttons.

Anchor coordinates are exchanged with the caller in the SVG viewBox
coordinate space returned by ``logic_gfx_to_svg.gfx_to_svg`` (already
normalised so ``(0, 0)`` corresponds to the top-left of the SVG's
viewBox contents), matching the format cached in
``GfxFileEditor.library_svg_images[library_id][symbol_name][2]``.

The dialog does not touch the underlying ``.HSL4`` library file. The
caller is expected to persist saved anchor changes via
``logic_library_anchor_overrides.LibraryAnchorOverridesStore``.
"""

