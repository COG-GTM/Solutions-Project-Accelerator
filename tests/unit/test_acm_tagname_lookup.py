"""Tagname -> ACM object lookup must not guess between near-identical names.

SPA-generated object names (``UX00201``, ``UX00202``, ``UX00203``...) differ by a single
character, which is below the noise floor of a fuzzy string score. The lookup therefore
normalizes both sides, prefers exact then substring matches, and only falls back to a
fuzzy match when it clears a high cutoff and clearly beats the runner-up.

Documents name the same object twice - "Raw Feed Transfer Pump A P-2010A (UX00201)" - so a
failed lookup retries with the bracketed tag from the line the tagname came from.
"""

import pandas as pd
import pytest

from bin.logic_acm_data_handler import ACM_Data_Handler
from bin.logic_text_document_llm_processors import context_source_text, lookup_acm_object


OBJECT_NAMES = [
    'UX00203', 'UX00201', 'UX00202', 'UX00501',
    'UX00701', 'UX00703', 'UX00702', 'UX00801', 'UX00802',
    'P-2010A Pump',
]


@pytest.fixture
def handler():
    # The lookup only touches the cached objects frame, so skip the DB-bound __init__.
    handler = object.__new__(ACM_Data_Handler)
    handler._ACM_Data_Handler__all_objects_df = pd.DataFrame(
        {'Name': OBJECT_NAMES}, index=range(1, len(OBJECT_NAMES) + 1)
    )
    return handler


def names_for(handler, tagname):
    return list(handler.get_object_with_tagname_like(tagname)['Name'])


@pytest.mark.parametrize('tagname', ['UX00201', 'ux00201', 'UX-00201', ' UX00201 ', 'UX_00201'])
def test_exact_match_survives_formatting(handler, tagname):
    assert names_for(handler, tagname) == ['UX00201']


def test_substring_match_returns_every_candidate(handler):
    assert sorted(names_for(handler, 'UX0020')) == ['UX00201', 'UX00202', 'UX00203']


def test_substring_match_ignores_separators(handler):
    assert names_for(handler, 'P-2010A') == ['P-2010A Pump']


@pytest.mark.parametrize('tagname', ['LIC-2001', 'UX0090', 'UX00204', ''])
def test_unknown_tagname_returns_empty_rather_than_a_guess(handler, tagname):
    assert handler.get_object_with_tagname_like(tagname).empty


def test_empty_object_cache_returns_empty():
    handler = object.__new__(ACM_Data_Handler)
    handler._ACM_Data_Handler__all_objects_df = pd.DataFrame()
    assert handler.get_object_with_tagname_like('UX00201').empty


INTERLOCK_LIST = '\n'.join([
    'Raw Feed Transfer Pump A P-2010A (UX00201)',
    'Suction tank level LIC-2001 > Lo',
    'Discharge pressure PI-2008 > LoLo',
    'Raw Feed Transfer Pump B P-2010B (UX00202)',
    'Tank high high level switch LSHH-2002 healthy',
    'Primary Reactor Agitator R-5010 (UX00501)',
])


def alias_lookup(handler, tagname, source_text=INTERLOCK_LIST):
    objects_df = lookup_acm_object(handler, tagname, source_text)
    return list(objects_df['Name']) if not objects_df.empty else []


@pytest.fixture
def spa_handler(handler):
    # As generated by SPA: only the UX tags exist, the equipment tags are document-only.
    objects_df = handler._ACM_Data_Handler__all_objects_df
    handler._ACM_Data_Handler__all_objects_df = objects_df[objects_df['Name'].str.startswith('UX')]
    return handler


@pytest.mark.parametrize('tagname, expected', [
    ('P-2010A', ['UX00201']),
    ('P-2010B', ['UX00202']),
    ('R-5010', ['UX00501']),
])
def test_equipment_tag_resolves_through_its_bracketed_object_tag(spa_handler, tagname, expected):
    assert alias_lookup(spa_handler, tagname) == expected


@pytest.mark.parametrize('tagname', ['LIC-2001', 'PI-2008', 'P-9999'])
def test_tag_without_a_bracketed_reference_stays_unresolved(spa_handler, tagname):
    assert alias_lookup(spa_handler, tagname) == []


def test_alias_is_never_borrowed_from_another_line(spa_handler):
    # 'P-2010A' appears only beside UX00201, so UX00202 on the next entry is off limits.
    assert alias_lookup(spa_handler, 'P-2010A', INTERLOCK_LIST) == ['UX00201']


def test_two_bracketed_tags_on_one_line_are_too_ambiguous_to_use(spa_handler):
    line = 'Transfer Pump P-2010A (UX00201) replaces (UX00202)'
    assert alias_lookup(spa_handler, 'P-2010A', line) == []


def test_object_named_in_acm_never_reaches_the_alias_fallback(handler):
    assert alias_lookup(handler, 'P-2010A') == ['P-2010A Pump']


def test_context_source_text_flattens_the_keys_that_carry_text():
    source = context_source_text('Suction tank level LIC-2001 > Lo', {
        'list_heading': 'Raw Feed Transfer Pump A P-2010A (UX00201)',
        'full_list': INTERLOCK_LIST,
        'row_and_column': (1, 2),
    })
    assert 'P-2010A (UX00201)' in source
    assert 'LIC-2001' in source
    assert '(1, 2)' not in source
